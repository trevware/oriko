let byZone: Map<string, string> | null = null;

/** The two-letter country a time zone belongs to, or null for one that names none (UTC). */
export function countryOfZone(zone: string): string | null {
  if (!byZone) {
    byZone = new Map();
    for (const [country, zones] of Object.entries(ZONES_BY_COUNTRY)) {
      for (const name of zones.split(" ")) byZone.set(name, country);
    }
  }
  return byZone.get(zone) ?? null;
}
